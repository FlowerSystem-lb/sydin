create or replace function public.complete_pick_list(
  p_pick_list_id bigint,
  p_deduct_stock boolean
)
returns public.pick_lists
language plpgsql
security definer
set search_path = public
as $$
declare
  authenticated_user_id uuid;
  completed_list public.pick_lists%rowtype;
  line_count integer;
  line_record record;
  quantity_before integer;
begin
  authenticated_user_id := auth.uid();

  if authenticated_user_id is null then
    raise exception 'Authentication is required.'
      using errcode = '42501';
  end if;

  select *
  into completed_list
  from public.pick_lists
  where id = p_pick_list_id
  for update;

  if not found or completed_list.user_id <> authenticated_user_id then
    raise exception 'Pick list not found.'
      using errcode = '42501';
  end if;

  if completed_list.status <> 'preparing' then
    raise exception 'Only preparing pick lists can be completed.'
      using errcode = '55000';
  end if;

  if p_deduct_stock is null then
    raise exception 'Choose whether completion should deduct stock.'
      using errcode = '23514';
  end if;

  perform pli.id
  from public.pick_list_items pli
  where pli.pick_list_id = p_pick_list_id
  order by pli.id
  for update;

  select count(*)
  into line_count
  from public.pick_list_items
  where pick_list_id = p_pick_list_id;

  if line_count = 0 then
    raise exception 'Add at least one item before completing this pick list.'
      using errcode = '23514';
  end if;

  if exists (
    select 1
    from public.pick_list_items
    where pick_list_id = p_pick_list_id
      and prepared_quantity <> required_quantity
  ) then
    raise exception 'Every item must be fully prepared before completion.'
      using errcode = '23514';
  end if;

  if p_deduct_stock then
    if exists (
      select 1
      from public.pick_list_items
      where pick_list_id = p_pick_list_id
        and inventory_item_id is null
    ) then
      raise exception
        'A linked inventory item is no longer available. Complete without deduction or remove the line before completion.'
        using errcode = '23514';
    end if;

    perform i.id
    from public.inventory i
    join public.pick_list_items pli
      on pli.inventory_item_id = i.id
    where pli.pick_list_id = p_pick_list_id
    order by i.id
    for update of i;

    for line_record in
      select
        pli.id as pick_list_item_id,
        pli.inventory_item_id,
        pli.required_quantity,
        pli.item_name_snapshot,
        i.user_id as inventory_user_id,
        i.quantity as inventory_quantity
      from public.pick_list_items pli
      join public.inventory i on i.id = pli.inventory_item_id
      where pli.pick_list_id = p_pick_list_id
      order by i.id
    loop
      if line_record.inventory_user_id <> authenticated_user_id then
        raise exception 'Inventory item ownership does not match the pick list.'
          using errcode = '42501';
      end if;

      if line_record.inventory_quantity < line_record.required_quantity then
        raise exception 'Insufficient stock for %.', line_record.item_name_snapshot
          using errcode = '23514';
      end if;

      if exists (
        select 1
        from public.stock_movements sm
        where sm.pick_list_item_id = line_record.pick_list_item_id
      ) then
        raise exception 'Stock has already been deducted for this pick list item.'
          using errcode = '23505';
      end if;

      quantity_before := line_record.inventory_quantity;

      update public.inventory
      set quantity = quantity_before - line_record.required_quantity
      where id = line_record.inventory_item_id
        and user_id = authenticated_user_id;

      insert into public.stock_movements (
        user_id,
        item_id,
        movement_type,
        quantity_delta,
        quantity_before,
        quantity_after,
        notes,
        pick_list_id,
        pick_list_item_id
      )
      values (
        authenticated_user_id,
        line_record.inventory_item_id,
        'stock_out',
        -line_record.required_quantity,
        quantity_before,
        quantity_before - line_record.required_quantity,
        'Pick list #' || p_pick_list_id || ': ' || completed_list.title,
        p_pick_list_id,
        line_record.pick_list_item_id
      );
    end loop;
  end if;

  perform set_config('sydin.complete_pick_list', 'on', true);

  update public.pick_lists
  set
    status = 'completed',
    completion_stock_action = case
      when p_deduct_stock then 'deducted'
      else 'skipped'
    end,
    completed_at = now(),
    cancelled_at = null
  where id = p_pick_list_id
  returning * into completed_list;

  return completed_list;
end;
$$;

