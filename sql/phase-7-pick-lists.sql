create table if not exists public.pick_lists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  customer_name text null,
  due_date date null,
  status text not null default 'draft',
  notes text null,
  completion_stock_action text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz null,
  cancelled_at timestamptz null,
  constraint pick_lists_title_not_blank check (btrim(title) <> ''),
  constraint pick_lists_status_valid check (
    status in ('draft', 'preparing', 'completed', 'cancelled')
  ),
  constraint pick_lists_completion_stock_action_valid check (
    completion_stock_action is null
    or completion_stock_action in ('deducted', 'skipped')
  ),
  constraint pick_lists_terminal_state_consistent check (
    (
      status in ('draft', 'preparing')
      and completion_stock_action is null
      and completed_at is null
      and cancelled_at is null
    )
    or (
      status = 'completed'
      and completion_stock_action in ('deducted', 'skipped')
      and completed_at is not null
      and cancelled_at is null
    )
    or (
      status = 'cancelled'
      and completion_stock_action is null
      and completed_at is null
      and cancelled_at is not null
    )
  )
);

create table if not exists public.pick_list_items (
  id bigint generated by default as identity primary key,
  pick_list_id bigint not null references public.pick_lists(id) on delete cascade,
  inventory_item_id bigint null references public.inventory(id) on delete set null,
  required_quantity integer not null,
  prepared_quantity integer not null default 0,
  notes text null,
  item_name_snapshot text not null,
  item_code_snapshot text null,
  sku_snapshot text null,
  unit_label_snapshot text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pick_list_items_required_quantity_positive check (
    required_quantity > 0
  ),
  constraint pick_list_items_prepared_quantity_valid check (
    prepared_quantity >= 0
    and prepared_quantity <= required_quantity
  ),
  constraint pick_list_items_name_snapshot_not_blank check (
    btrim(item_name_snapshot) <> ''
  )
);

