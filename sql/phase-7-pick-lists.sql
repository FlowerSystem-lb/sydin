create trigger pick_list_items_normalize_validate
before insert or update on public.pick_list_items
for each row
execute function public.normalize_and_validate_pick_list_item();

create or replace function public.guard_pick_list_item_delete()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  owner_id uuid;
  parent_status text;
begin
  if pg_trigger_depth() > 1 then
    return old;
  end if;

  select pl.user_id, pl.status
  into owner_id, parent_status
  from public.pick_lists pl
  where pl.id = old.pick_list_id;

  if auth.uid() is null or owner_id <> auth.uid() then
    raise exception 'Pick list item must belong to the authenticated user.'
      using errcode = '42501';
  end if;

  if parent_status not in ('draft', 'preparing') then
    raise exception 'Completed or cancelled pick list items cannot be removed.'
      using errcode = '55000';
  end if;

  return old;
end;
$$;

drop trigger if exists pick_list_items_guard_delete
  on public.pick_list_items;
create trigger pick_list_items_guard_delete
before delete on public.pick_list_items
for each row
execute function public.guard_pick_list_item_delete();

create or replace function public.prevent_active_pick_list_inventory_delete()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if exists (
    select 1
    from public.pick_list_items pli
    join public.pick_lists pl on pl.id = pli.pick_list_id
    where pli.inventory_item_id = old.id
      and pl.status in ('draft', 'preparing')
  ) then
    raise exception
      'This inventory item belongs to an active pick list. Remove it from the pick list before deleting it.'
      using errcode = '55000';
  end if;

  return old;
end;
$$;

