create or replace function public.enforce_pick_list_active_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  effective_plan text := 'free';
  active_limit integer;
  active_count integer;
begin
  if auth.uid() is null or new.user_id <> auth.uid() then
    raise exception 'Pick list must belong to the authenticated user.'
      using errcode = '42501';
  end if;

  select case
    when lower(coalesce(us.status, '')) = 'active'
      then lower(coalesce(us.plan, 'free'))
    else 'free'
  end
  into effective_plan
  from public.user_subscriptions us
  where us.user_id = new.user_id;

  effective_plan := coalesce(effective_plan, 'free');

  if effective_plan = 'pro' then
    return new;
  end if;

  active_limit := case
    when effective_plan = 'standard' then 50
    else 3
  end;

  select count(*)
  into active_count
  from public.pick_lists pl
  where pl.user_id = new.user_id
    and pl.status in ('draft', 'preparing');

  if active_count >= active_limit then
    raise exception 'Active Pick List limit reached for the current plan.'
      using errcode = 'P0001';
  end if;

  return new;
end;
$$;

drop trigger if exists pick_lists_enforce_active_limit
  on public.pick_lists;
create trigger pick_lists_enforce_active_limit
before insert on public.pick_lists
for each row
execute function public.enforce_pick_list_active_limit();

create or replace function public.normalize_pick_list()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.title = btrim(new.title);
  new.customer_name = nullif(btrim(new.customer_name), '');
  new.notes = nullif(btrim(new.notes), '');

  if tg_op = 'INSERT' then
    if new.status <> 'draft' then
      raise exception 'New pick lists must start as draft.'
        using errcode = '23514';
    end if;

    new.completion_stock_action = null;
    new.completed_at = null;
    new.cancelled_at = null;
    return new;
  end if;

  if new.user_id is distinct from old.user_id then
    raise exception 'Pick list ownership cannot be changed.'
      using errcode = '23514';
  end if;

  if old.status in ('completed', 'cancelled') then
    raise exception 'Completed or cancelled pick lists cannot be changed.'
      using errcode = '55000';
  end if;

  if old.status = 'draft'
     and new.status not in ('draft', 'preparing', 'cancelled') then
    raise exception 'Invalid pick list status transition.'
      using errcode = '23514';
  end if;

  if old.status = 'preparing'
     and new.status not in ('preparing', 'completed', 'cancelled') then
    raise exception 'Invalid pick list status transition.'
      using errcode = '23514';
  end if;

  if new.status = 'completed'
     and coalesce(
       current_setting('sydin.complete_pick_list', true),
       ''
     ) <> 'on' then
    raise exception 'Pick lists must be completed through complete_pick_list.'
      using errcode = '42501';
  end if;

  if new.status = 'cancelled' then
    new.cancelled_at = coalesce(new.cancelled_at, now());
    new.completed_at = null;
    new.completion_stock_action = null;
  elsif new.status in ('draft', 'preparing') then
    new.cancelled_at = null;
    new.completed_at = null;
    new.completion_stock_action = null;
  end if;

  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists pick_lists_normalize on public.pick_lists;
create trigger pick_lists_normalize
before insert or update on public.pick_lists
for each row
execute function public.normalize_pick_list();

create or replace function public.normalize_and_validate_pick_list_item()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  owner_id uuid;
  parent_status text;
begin
  new.item_name_snapshot = btrim(new.item_name_snapshot);
  new.item_code_snapshot = nullif(btrim(new.item_code_snapshot), '');
  new.sku_snapshot = nullif(btrim(new.sku_snapshot), '');
  new.unit_label_snapshot = nullif(btrim(new.unit_label_snapshot), '');
  new.notes = nullif(btrim(new.notes), '');

  select pl.user_id, pl.status
  into owner_id, parent_status
  from public.pick_lists pl
  where pl.id = new.pick_list_id;

  if owner_id is null then
    raise exception 'Pick list not found.'
      using errcode = '23503';
  end if;

  if auth.uid() is null or owner_id <> auth.uid() then
    raise exception 'Pick list item must belong to the authenticated user.'
      using errcode = '42501';
  end if;

  if parent_status not in ('draft', 'preparing') then
    if tg_op = 'UPDATE'
       and old.inventory_item_id is not null
       and new.inventory_item_id is null
       and new.pick_list_id = old.pick_list_id
       and new.required_quantity = old.required_quantity
       and new.prepared_quantity = old.prepared_quantity
       and new.notes is not distinct from old.notes
       and new.item_name_snapshot = old.item_name_snapshot
       and new.item_code_snapshot is not distinct from old.item_code_snapshot
       and new.sku_snapshot is not distinct from old.sku_snapshot
       and new.unit_label_snapshot is not distinct from old.unit_label_snapshot then
      new.updated_at = old.updated_at;
      return new;
    end if;

    raise exception 'Completed or cancelled pick list items cannot be changed.'
      using errcode = '55000';
  end if;

  if new.inventory_item_id is not null
     and not exists (
       select 1
       from public.inventory i
       where i.id = new.inventory_item_id
         and i.user_id = owner_id
     ) then
    raise exception 'Inventory item must belong to the pick list owner.'
      using errcode = '23514';
  end if;

  if tg_op = 'UPDATE' then
    if new.pick_list_id is distinct from old.pick_list_id then
      raise exception 'Pick list items cannot be moved between lists.'
        using errcode = '23514';
    end if;

    new.updated_at = now();
  end if;

  return new;
end;
$$;

