-- SydIN Phase 8: Purchase Orders (persisted history, expenses, receive-to-stock)
-- Run manually in the Supabase SQL editor after reviewing.
--
-- Follows the conventions of phase-7-pick-lists.sql:
--   * per-user rows guarded by RLS,
--   * stock only changes through stock_movements,
--   * terminal statuses locked down, receive flow gated behind an RPC.

begin;

create table if not exists public.purchase_orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  po_number text not null,
  title text null,
  supplier_id bigint null references public.suppliers(id) on delete set null,
  supplier_name_snapshot text null,
  supplier_contact_snapshot text null,
  depot_id bigint null references public.depots(id) on delete set null,
  depot_name_snapshot text null,
  purchase_date date null,
  expected_delivery_date date null,
  status text not null default 'draft',
  payment_method text null,
  paid_by text null,
  payment_status text not null default 'unpaid',
  amount_paid numeric(12, 2) null,
  currency_code text null,
  notes text null,
  internal_reference text null,
  attachment_url text null,
  attachment_label text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  received_at timestamptz null,
  cancelled_at timestamptz null,
  constraint purchase_orders_po_number_not_blank check (btrim(po_number) <> ''),
  constraint purchase_orders_status_valid check (
    status in ('draft', 'ordered', 'received', 'cancelled')
  ),
  constraint purchase_orders_payment_method_valid check (
    payment_method is null
    or payment_method in ('cash', 'card', 'transfer', 'other')
  ),
  constraint purchase_orders_payment_status_valid check (
    payment_status in ('unpaid', 'partial', 'paid')
  ),
  constraint purchase_orders_amount_paid_valid check (
    amount_paid is null or amount_paid >= 0
  ),
  constraint purchase_orders_terminal_state_consistent check (
    (
      status in ('draft', 'ordered')
      and received_at is null
      and cancelled_at is null
    )
    or (status = 'received' and received_at is not null and cancelled_at is null)
    or (status = 'cancelled' and received_at is null and cancelled_at is not null)
  )
);

create table if not exists public.purchase_order_lines (
  id bigint generated by default as identity primary key,
  purchase_order_id bigint not null references public.purchase_orders(id) on delete cascade,
  line_type text not null default 'inventory',
  inventory_item_id bigint null references public.inventory(id) on delete set null,
  affects_stock boolean not null default false,
  expense_category text null,
  name_snapshot text not null,
  sku_snapshot text null,
  item_code_snapshot text null,
  unit_label_snapshot text null,
  quantity numeric(12, 2) not null default 1,
  unit_cost numeric(12, 2) null,
  notes text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint purchase_order_lines_type_valid check (
    line_type in ('inventory', 'expense')
  ),
  constraint purchase_order_lines_expense_category_valid check (
    expense_category is null
    or expense_category in (
      'equipment', 'maintenance', 'supplies', 'services', 'utilities', 'other'
    )
  ),
  constraint purchase_order_lines_quantity_positive check (quantity > 0),
  constraint purchase_order_lines_unit_cost_valid check (
    unit_cost is null or unit_cost >= 0
  ),
  constraint purchase_order_lines_name_not_blank check (
    btrim(name_snapshot) <> ''
  ),
  -- Expense lines never touch stock; inventory links belong to inventory lines only.
  constraint purchase_order_lines_expense_never_stock check (
    line_type <> 'expense' or (affects_stock = false and inventory_item_id is null)
  ),
  constraint purchase_order_lines_stock_needs_item check (
    affects_stock = false or inventory_item_id is not null
  )
);

create index if not exists purchase_orders_user_status_created_idx
  on public.purchase_orders(user_id, status, created_at desc);

create index if not exists purchase_orders_user_purchase_date_idx
  on public.purchase_orders(user_id, purchase_date desc);

create index if not exists purchase_orders_user_depot_idx
  on public.purchase_orders(user_id, depot_id);

create index if not exists purchase_order_lines_order_id_idx
  on public.purchase_order_lines(purchase_order_id);

create index if not exists purchase_order_lines_inventory_item_id_idx
  on public.purchase_order_lines(inventory_item_id);

alter table public.stock_movements
